#!/usr/bin/env python3
"""Supplementary Table S10: SecB-niche macrophage differential expression (Fig 6e; Xenium rows of Fig 6f,h).

Inputs (generated by figures/figure6/):
  02_fig6e_visium_hd_niche_volcano.py 16 / 8  -> visiumWT01_niche_vs_distal_volcano{,_8um}.csv   (Visium HD section of WT01, genome-wide)
  01_fig6abcd_visium_hd_bins.py                       -> visium_n2_bins_WT01.csv.gz (bin classes; counts in the README sheet)
  04_fig6fhi_xenium_niche_macrophages.R               -> mac_signature_deg_WT.csv, mac_counts_WT.csv      (Xenium whole tissues, 477-gene panel)
The Visium content adjustment, carry-over and stromal classes are identical to the Fig 6e volcano (the block of
figures/figure6/13_fig6_draw_panels.py that draws Fig6e_visium_niche_macrophage_volcano).
Sections are labelled with the de-identified study codes (WT01-WT08), read at run time from the private key
(never written out), as in figures/figure5/11_fig5_compose_panels.py.
Outputs: SuppTable10_secb_niche_macrophage_degs.xlsx (+ one CSV per sheet) via supp_xlsx.write_table.
Manuscript item(s): Table S10.
"""
import os, sys, numpy as np, pandas as pd
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); from supp_xlsx import write_table
O = os.path.join(os.environ.get("OUTPUT_ROOT", "output"), "fig6_singler")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from config.study_codes import code_map
WTCODE = code_map("Whole tissue")   # section name (source ID or code) -> study code; private key, never written out
VISIUM_SECTION = WTCODE["WT01"]   # the Visium HD section comes from this Xenium whole tissue
PANMAC = ["CD68", "CSF1R", "AIF1", "CD14", "FCGR3A", "TYROBP", "LAPTM5"]
STROMAL_SET = ["SPARC", "FN1", "DCN", "LUM", "POSTN", "TIMP3", "BGN", "MGP", "IGFBP7", "AEBP1", "CTHRC1", "VCAN", "TMSB4X", "VIM"]

def visium(f):
    V = pd.read_csv(f)
    adj = V[V.gene.isin(PANMAC)].log2FC.median()
    V["log2FC_content_adjusted"] = V.log2FC - adj
    strom = V.gene.str.startswith("COL") | V.gene.isin(STROMAL_SET)
    if "mac_sourced" in V:
        V["source_class"] = np.where(strom & (V.log2FC_content_adjusted < 0), "stromal (distal-enriched)",
                            np.where(V.mac_sourced, "macrophage-attributable", "SecB epithelial carry-over"))
    V["significant_FDR<0.05"] = V.fdr_bin < 0.05
    V = V.rename(columns={"log2FC": "log2FC_raw", "p_bin": "P_bin_MannWhitney", "fdr_bin": "FDR_bin_BH", "det_niche": "frac_bins_detected_niche",
                          "det_distal": "frac_bins_detected_distal", "mean_secb_epi": "mean_CP10k_SecBhigh_epithelial_bins",
                          "mean_niche": "mean_CP10k_niche_mac_bins", "mac_sourced": "passes_carryover_rule"})
    cols = ["gene", "log2FC_content_adjusted", "log2FC_raw", "P_bin_MannWhitney", "FDR_bin_BH", "significant_FDR<0.05", "source_class",
            "passes_carryover_rule", "frac_bins_detected_niche", "frac_bins_detected_distal", "mean_CP10k_niche_mac_bins", "mean_CP10k_SecBhigh_epithelial_bins"]
    V = V[[c for c in cols if c in V]].sort_values(["FDR_bin_BH", "log2FC_content_adjusted"], ascending=[True, False])
    num = V.select_dtypes("number").columns; V[num] = V[num].apply(lambda c: c.round(4) if c.name.startswith(("log2", "frac", "mean")) else c)
    return V, adj

V16, a16 = visium(f"{O}/visiumWT01_niche_vs_distal_volcano.csv")
V8, a8 = visium(f"{O}/visiumWT01_niche_vs_distal_volcano_8um.csv")
top = V16[(V16["significant_FDR<0.05"]) & (V16.source_class == "macrophage-attributable") & ~V16.gene.str.startswith("MT-")]
top = pd.concat([top[top.log2FC_content_adjusted > 0].sort_values("FDR_bin_BH").assign(direction="up in SecB-niche macrophage bins"),
                 top[top.log2FC_content_adjusted < 0].sort_values("FDR_bin_BH").assign(direction="up in distal macrophage bins")])
B = pd.read_csv(f"{O}/visium_n2_bins_WT01.csv.gz").cls.value_counts()

X = pd.read_csv(f"{O}/mac_signature_deg_WT.csv"); N = pd.read_csv(f"{O}/mac_counts_WT.csv")
secs = [c for c in X.columns if c in WTCODE]
X = X.rename(columns={"logFC": "log2FC_niche_vs_control", "AveExpr": "AveExpr_voom_logCPM", "n_up": "n_sections_up(>0.1)", "n_dn": "n_sections_down(<-0.1)",
                      "n_sec": "n_sections", **{s: f"log2FC_{WTCODE[s]}" for s in secs}}).drop(columns=["B"])
code_cols = sorted(f"log2FC_{WTCODE[s]}" for s in secs)   # per-section columns in study-code order
cols = list(X.columns); first = min(cols.index(c) for c in code_cols); rest = [c for c in cols if c not in code_cols]
X = X[rest[:first] + code_cols + rest[first:]]
X = X.sort_values("P.Value"); num = X.select_dtypes("number").columns.difference(["P.Value", "FDR"]); X[num] = X[num].round(4)
Ncnt = N.pivot(index="sample", columns="group", values="n").reset_index().rename(columns={"niche": "n_niche_macrophages", "ctrl": "n_control_macrophages"})
Ncnt["sample"] = Ncnt["sample"].map(WTCODE); Ncnt = Ncnt.sort_values("sample").reset_index(drop=True)
Ncnt["included_in_DE (>=50 each)"] = (Ncnt.n_niche_macrophages >= 50) & (Ncnt.n_control_macrophages >= 50)

write_table(10, "secb_niche_macrophage_degs",
    "Supplementary Table 10. Differential expression of macrophages in SecB niches (Visium HD and Xenium).",
    [f"Sheet Visium_16um (Figure 6e): Visium HD section {VISIUM_SECTION}, 16 um bins. Bins classified from raw marker UMIs: macrophage bin = >= 3 macrophage-marker UMIs "
     "(CD68, CD163, CSF1R, AIF1, C1QA/B/C, FCGR3A, CD14, LYZ) and >= epithelial-marker UMIs; pure epithelial bin = >= 5 epithelial UMIs (EPCAM, KRT8, KRT18, PAX8, WFDC2, MUC16) "
     "and no macrophage UMIs; SecB-high = top tertile of the SecB - SecA polarization score (7-gene signatures) among epithelial bins.",
     f"SecB-niche macrophage bins = >= 2 SecB-high bins within 3 bins (~48 um); distal = none (Fig 6 bin classification: {B.get('mac (SecB niche)', 0):,} niche and {B.get('mac (distal)', 0):,} distal bins). "
     "Genes detected in >= 5% of bins of either group were tested.",
     f"log2FC_raw = log2(mean CP10k niche + 0.01) - log2(mean CP10k distal + 0.01); log2FC_content_adjusted = log2FC_raw minus the median log2FC of pan-macrophage genes "
     f"({', '.join(PANMAC)}; median = {a16:.3f}) to remove differences in macrophage content per bin.",
     "Carry-over rule: a gene is attributable to macrophages only if its mean in niche macrophage bins >= its mean in pure SecB-high epithelial bins; otherwise it is "
     "classed as SecB epithelial carry-over (open circles in Fig 6e). Stromal class = collagens and matrix genes enriched in distal bins (triangles in Fig 6e).",
     "Statistics: bin-level two-sided Mann-Whitney U test with Benjamini-Hochberg FDR. Bins are not independent replicates and this is a single section, so P values are descriptive.",
     f"Sheet Visium_8um: the same analysis on 8 um bins (thresholds >= 2 macrophage and >= 3 epithelial UMIs, 6-bin radius ~48 um; pan-macrophage median = {a8:.3f}).",
     "Sheet Visium_top_macrophage_genes: significant (FDR < 0.05) macrophage-attributable genes from the 16 um analysis, excluding mitochondrial genes; ordered by FDR within direction.",
     "Sheet Xenium_niche_vs_control (Xenium rows of Figure 6f,h): Xenium whole tissues, SingleR labels, all cells; 7 sections enter the fit (WT07 had 39 SecB-niche macrophages, below the 50-macrophage minimum). SecB-niche macrophage = >= 5 SecB epithelial cells within 50 um; "
     "control macrophage = no SecB and >= 5 SecA cells within 50 um. Raw panel counts summed per section x group (pseudobulk); sections with >= 50 macrophages in each group; "
     "edgeR filterByExpr + TMM, limma-voom, design ~ section + group (paired). Per-section log2FC = log2((CPM niche + 1)/(CPM control + 1)); n_sections_up/down = sections with log2FC > 0.1 / < -0.1.",
     "Sheet Xenium_macrophage_counts: niche and control macrophages per section.",
     "Build: figures/figure6/02_fig6e_visium_hd_niche_volcano.py (16, 8), 04_fig6fhi_xenium_niche_macrophages.R -> tables/10_tableS10_secb_niche_macrophage_degs.py"],
    [("Visium_16um", V16), ("Visium_8um", V8), ("Visium_top_macrophage_genes", top), ("Xenium_niche_vs_control", X), ("Xenium_macrophage_counts", Ncnt)])
print("top up:", top[top.direction.str.startswith("up in SecB")].gene.head(12).tolist())
print(Ncnt.to_string(index=False))
